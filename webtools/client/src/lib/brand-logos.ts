/**
 * lib/brand-logos.ts — project / task logo resolution (local static images)
 *
 * Directory and naming (aligned with agx_image, set by Feng 2026-10-20):
 *   - project: `public/brand/projects/{project_id}.png`
 *   - task:    `public/brand/tasks/{task_labs}.png`
 *     ★ task_labs repeats (general / watchdog_alert / universal have 70+ rows each),
 *       so **one image is de-duplicated and shared per task_labs**; all task rows with the same labs show the
 *       same logo.
 *
 * Why an "explicit manifest" instead of "concatenating paths":
 *   concatenating paths = every image not generated 404s (a red console and flickering images).
 *   The manifest is auto-generated by `scripts/gen-brand-logos.mjs` scanning the directory -- run the script
 *   once when images are in place; other objects keep the initials fallback, 0 404s all the way.
 *
 * Resolution priority (implemented in component entity-logo.tsx):
 *   1. backend field (agx_project.project_logo / agx_task_base.task_logo)
 *   2. local brand image (the manifest in this file)
 *   3. initials + deterministic color
 *
 * ★ This file is generated by scripts/gen-brand-logos.mjs, do not edit by hand (edits are overwritten on the
 *   next generation).
 */

