/** Project logo: return the path on a manifest hit, otherwise an empty string (the caller falls back to initials). */
export function resolveBrandProjectLogo(id?: string): string {
  if (!id) return "";
  return BRAND_PROJECT_LOGOS[id] || "";
}

/** Task logo: resolve by task_labs (passing task_id, convert it to labs in the caller first). */
export function resolveBrandTaskLogo(labs?: string): string {
  if (!labs) return "";
  return BRAND_TASK_LOGOS[labs] || "";
}
